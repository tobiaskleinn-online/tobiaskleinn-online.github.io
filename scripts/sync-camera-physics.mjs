/** Import an upstream camera-lab snapshot without changing that project. */
import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';
const root = path.resolve(import.meta.dirname, '..');
const source = path.resolve(
	process.argv[2] || path.join(root, '../../chatGPT_area/camera-lab/dist'),
);
const target = path.join(root, 'public/camera-physics');
await fs.mkdir(target, { recursive: true });
for (const item of await fs.readdir(source, { withFileTypes: true })) {
	if (
		(item.isFile() && /\.(js|txt)$/.test(item.name) && item.name !== 'de.js') ||
		item.name === 'images'
	) {
		await fs.cp(path.join(source, item.name), path.join(target, item.name), { recursive: true });
	}
}
await fs.rm(path.join(target, 'de.js'), { force: true });
await fs.copyFile(
	path.join(root, 'src/assets/fonts/inter-latin-variable.woff2'),
	path.join(target, 'inter.woff2'),
);
let html = await fs.readFile(path.join(source, 'index.html'), 'utf8');
html = html.match(/<body[^>]*>([\s\S]*)<\/body>/)[1];
html = html.replace(/<header class="site-header">[\s\S]*?<\/header>/, '');
html = html.replace(/<script\b[\s\S]*?<\/script>/g, '');
html = html.replace('<main>', '<div class="camera-main">').replace('</main>', '</div>');
html = html.replace(/<footer>[\s\S]*?<\/footer>/, '');
html = html.replace(/<section id="explore"[\s\S]*?<\/section>/, '');
html = html.replace(
	/<div class="module-identity">[\s\S]*?<\/div>/,
	'<div class="module-identity"><strong>Camera &amp; optics</strong></div>',
);
html = html.replace('Camera &amp; Optics Basics', 'Camera and optics basics');
html = html.replace('<aside id="camera-controls"', '<aside hidden id="camera-controls"');
await fs.writeFile(path.join(root, 'src/data/camera-physics.html'), html);
// Keep module selectors from affecting the shared portfolio header, footer or gallery.
const css = postcss.parse(await fs.readFile(path.join(source, 'style.css'), 'utf8'));
css.walkAtRules('import', (rule) => rule.remove());
css.walkRules((rule) => {
	if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
	if (rule.selectors.some((s) => s === ':root' || s === 'html[data-theme=dark]')) {
		rule.remove();
		return;
	}
	rule.selector = selectorParser((selectors) => {
		selectors.each((selector) => {
			selector.walkTags((tag) => {
				if (tag.value === 'main')
					tag.replaceWith(selectorParser.className({ value: 'camera-main' }));
			});
		});
	}).processSync(rule.selector);
	rule.selectors = rule.selectors.map((selector) => {
		if (selector.startsWith('body'))
			return selector.replace(/^body(?:\.camera-physics-app)?/, '.camera-app');
		const match = selector.match(/^(html(?:\[[^\]]*\])?)(.*)$/);
		if (match) return `${match[1]} .camera-app${match[2]}`;
		return `.camera-app ${selector}`;
	});
});
css.walkDecls((decl) => {
	if (decl.prop === 'font-family') decl.value = "'Inter', system-ui, sans-serif";
	if (decl.prop === 'box-shadow') decl.value = 'none';
	// Neutralize interface chrome; explanatory SVGs and photographic content retain color.
	if (/\.gold|\.blue|\.live|\.viewfinder/.test(decl.parent.selector || '')) return;
	if (/^#[\da-f]{3,8}$/i.test(decl.value)) {
		if (decl.prop === 'color')
			decl.value = /^#fff(?:fff)?$/i.test(decl.value) ? 'var(--on-accent)' : 'var(--muted)';
		if (decl.prop === 'background' || decl.prop === 'background-color')
			decl.value = /\.primary|\.compare-toggle\.selected/.test(decl.parent.selector || '')
				? 'var(--accent)'
				: 'var(--surface)';
		if (decl.prop === 'border-color') decl.value = 'var(--line)';
	}
});
await fs.writeFile(
	path.join(root, 'src/styles/camera-physics-import.css'),
	`/* Generated by npm run sync:camera. Scoped upstream layout. */\n${css.toString()}`,
);
// The portfolio owns theme selection. Existing diagrams already observe data-theme.
await fs.writeFile(path.join(target, 'theme.js'), 'export function setupTheme() {}\n');
// English only for the integrated site, independent of any old saved language setting.
await fs.writeFile(
	path.join(target, 'i18n.js'),
	`export const getLanguage=()=> 'en';\nexport const translateText=text=>text;\nexport function localize(){}\nexport function setupLanguage(){document.documentElement.lang='en';}\n`,
);
// Resolve asset paths relative to their module, rather than the Astro page URL.
for (const name of ['portrait-asset.js', 'portrait-background-asset.js', 'night-asset.js']) {
	const file = path.join(target, name);
	const code = (await fs.readFile(file, 'utf8')).replace(
		/='(images\/[^']+)'/,
		"=new URL('./$1',import.meta.url).href",
	);
	await fs.writeFile(file, code);
}
let app = await fs.readFile(path.join(target, 'app.js'), 'utf8');
app = app.replace(
	"import {setupPortrait3D} from './portrait-3d.js';",
	"import {setupPortrait3D} from './portfolio-portrait.js';",
);
app = app.replace(
	/function page\(id\)\{[\s\S]*?\n(?=document\.querySelectorAll\('\[data-page\]'\))/,
	`function page(id){
 if(id==='equiv')id='tools';
 if(!['lab','learn','tools'].includes(id))id='lab';
 $('camera-controls').hidden=id!=='lab';
 document.querySelector('.module-header').hidden=false;
 document.querySelectorAll('.camera-app .page').forEach(el=>el.hidden=el.id!==id);
 document.querySelectorAll('.camera-app .nav').forEach(el=>{const active=el.dataset.page===id;el.classList.toggle('active',active);if(active)el.setAttribute('aria-current','page');else el.removeAttribute('aria-current')});
 if(id==='lab')update();
 history.replaceState(null,'','#'+id);
 document.title=({lab:'Camera Lab',learn:'Camera and optics basics',tools:'Tools'}[id])+' — Camera & optics — Tobias Klein';
}\n`,
);
app = app.replace(
	";$('footer-lab').onclick=()=>{page('explore');window.scrollTo({top:0,behavior:'smooth'})};",
	';',
);
await fs.writeFile(path.join(target, 'app.js'), app);
// The heavy scene documents are fetched only when the camera lab is actually opened.
let scenes = await fs.readFile(path.join(target, 'integrated-scenes.js'), 'utf8');
scenes = scenes.replace("import {de} from './de.js';", '');
scenes = scenes.replace(
	/const dictionary=\{[\s\S]*?\};\n function control/,
	'const dictionary={};\n function control',
);
scenes = scenes.replace(
	"import {sceneDocuments} from './scene-documents.js';",
	"import {adaptScene} from './portfolio-scenes.js';",
);
scenes = scenes.replace(
	'function sync(v,s){if(s.key!==key)',
	"function sync(v,s){if(document.getElementById('lab').hidden)return;if(s.key!==key)",
);
scenes = scenes.replace(
	'frame.srcdoc=sceneDocuments[key];',
	"const requested=key;import('./scene-documents.js').then(({sceneDocuments})=>{if(key===requested)frame.srcdoc=adaptScene(sceneDocuments[key]);}).catch(()=>{frame.srcdoc='<p>The 3D scene could not load. Reload to try again.</p>';});",
);
await fs.writeFile(path.join(target, 'integrated-scenes.js'), scenes);
await fs.writeFile(
	path.join(target, 'portfolio-portrait.js'),
	`// Compatibility for the older portrait view; load its engine only if requested.\nexport function setupPortrait3D(host, onMove) { let viewer, latest; const api = {update(...args){latest=args;viewer?.update(...args)},setSubject(...args){viewer?.setSubject(...args)},setView(...args){viewer?.setView(...args)},reset(){viewer?.reset()}}; import('./vendor-3d.js').then(()=>import('./portrait-3d.js')).then(module=>{viewer=module.setupPortrait3D(host,onMove);if(latest)viewer.update(...latest)}).catch(()=>{host.textContent='The 3D view could not load. Please reload.'}); return api; }\n`,
);
// Give self-contained 3D documents the same neutral foundation and local Inter font.
const tokens = await fs.readFile(path.join(root, 'src/styles/tokens.css'), 'utf8');
const [light, rest] = tokens.split(':root[data-theme=');
const palette = (text) =>
	Object.fromEntries([...text.matchAll(/--([\w-]+):\s*(#[\da-f]{6})/gi)].map((m) => [m[1], m[2]]));
const themes = { light: palette(light), dark: palette(rest.split(':root {')[0]) };
const sliderCSS = await fs.readFile(path.join(root, 'src/styles/slider-controls.css'), 'utf8');
await fs.writeFile(
	path.join(target, 'portfolio-scenes.js'),
	`const themes=${JSON.stringify(themes)};\nconst sliders=${JSON.stringify(sliderCSS)};\nexport function adaptScene(html){const font='data:font/woff2;base64,${(await fs.readFile(path.join(root, 'src/assets/fonts/inter-latin-variable.woff2'))).toString('base64')}';let css='@font-face{font-family:Inter;src:url('+font+') format("woff2");font-weight:100 900;font-display:swap}:root,body,button,input,select{font-family:Inter,system-ui,sans-serif!important}';for(const [key,p]of Object.entries(themes)){css+='html[data-theme='+key+']{--paper:'+p.paper+';--surface:'+p.soft+';--ink:'+p.ink+';--muted:'+p.quiet+';--line:'+p.line+';--accent:'+p.ink+';--accent-soft:'+p.soft+';--on-accent:'+p.paper+';--bg:'+p.paper+';--soft:'+p.soft+';--slider-track:'+p['slider-track']+';--slider-thumb:'+p['slider-thumb']+';--slider-focus:'+p['slider-focus']+';color-scheme:'+key+'}'}return html.replace('</head>','<style>'+css+sliders+'</style></head>');}\n`,
);
console.log(
	'Imported cameraPhysics markup, scoped styles and runtime assets. Upstream project unchanged.',
);
